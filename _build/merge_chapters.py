# -*- coding: utf-8 -*-
import io
import os

BASE = os.path.dirname(os.path.abspath(__file__))
NOTES = os.path.join(os.path.dirname(BASE), "黑马Java课程笔记")


def merge(chapter_file, header, parts):
    chunks = [header.strip()]
    for p in parts:
        path = os.path.join(BASE, p)
        with io.open(path, encoding="utf-8") as f:
            chunks.append(f.read().strip())
    text = "\n\n".join(chunks) + "\n"
    out = os.path.join(NOTES, chapter_file)
    with io.open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(out, len(text.splitlines()), "lines")


