package com.heima.ch05;

// ==================== 示例代码 ====================

public class MethodOverload {
    public static void main(String[] args) {
        // 方法名相同，按实参自动匹配不同的方法
        System.out.println(sum(1, 2));     // 匹配两个 int
        System.out.println(sum(1, 2, 3));  // 匹配三个 int
        System.out.println(sum(1.5, 2.5)); // 匹配两个 double
    }

    // 两个 int 求和
    public static int sum(int a, int b) {
        return a + b;
    }

    // 参数个数不同，构成重载
    public static int sum(int a, int b, int c) {
        return a + b + c;
    }

    // 参数类型不同，也构成重载
    public static double sum(double a, double b) {
        return a + b;
    }
}

