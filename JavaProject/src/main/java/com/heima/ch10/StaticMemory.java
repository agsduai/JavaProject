package com.heima.ch10;

// ==================== 示例代码 ====================

// 内存变化演示（结合注释画出内存图）
// 1. StaticMemoryStaticPerson.class 加载进方法区（元空间）
// 2. 静态变量 country 在堆的静态存储位置出现，先为默认值 null，后赋值"中国"
// 3. main 进栈
// 4. new StaticMemoryStaticPerson()：堆中开辟对象空间（里面只有 name），地址 0x0011 给 p1
// 5. new StaticMemoryStaticPerson()：堆中再开一块（也只有 name），地址 0x0022 给 p2
//    注意：country 不在任何对象空间里，它在静态位置，全类只有一份
public class StaticMemory {
    public static void main(String[] args) {
        StaticMemoryStaticPerson p1 = new StaticMemoryStaticPerson();
        p1.name = "阿玮";

        StaticMemoryStaticPerson p2 = new StaticMemoryStaticPerson();
        p2.name = "小黑";

        // 类名和两个对象访问到的都是静态位置那同一份
        System.out.println(StaticMemoryStaticPerson.country); // 中国
        p1.country = "华夏";
        System.out.println(p2.country);           // 华夏（改的是共享的那一份）
        System.out.println(StaticMemoryStaticPerson.country); // 华夏
    }
}

class StaticMemoryStaticPerson {
    String name;                  // 非静态成员变量：随对象存放在堆的对象空间里
    public static String country; // 静态变量：存放在堆的静态存储位置，全类一份
}

