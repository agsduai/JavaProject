package com.heima.ch56;

import java.util.LinkedHashMap;
import java.util.Map;

// ==================== 示例代码 ====================

public class AnnualCapacityPlan {
    static void plan() {
        System.out.println("【年度容量规划表（示意）】");
        Map<String, String> rows = new LinkedHashMap<>();
        rows.put("业务预测", "GMV +60%，订单 5.4 亿 -> 8 亿（52-01）");
        rows.put("资源换算", "核心服务节点 40 -> 60；GPU 12 -> 18 卡");
        rows.put("弹性策略", "日常 60 常驻 + 峰值弹性（47-08）");
        rows.put("成本目标", "单位订单成本 -15%（缓存+批处理替代）");
        rows.put("联动里程碑", "M5 容器化 -> M7 湖仓（52-09）");
        rows.forEach((k, v) -> System.out.printf("  %-6s %s%n", k, v));
        System.out.println();
        System.out.println("  季度滚动修正：实际增长 vs 预测偏差 >20% 触发重估");
    }

    public static void main(String[] args) {
        plan();
    }
}

