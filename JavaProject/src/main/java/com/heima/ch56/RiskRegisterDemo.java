package com.heima.ch56;

import java.util.ArrayList;
import java.util.List;

// ==================== 示例代码 ====================

public class RiskRegisterDemo {
    record Risk(String desc, int prob, int impact, String mitigation, String owner) {
        int score() {
            return prob * impact;
        }
    }

    public static void main(String[] args) {
        List<Risk> risks = new ArrayList<>(List.of(
                new Risk("订单库单点", 2, 5, "M4 分库分表（52-09）", "数据组"),
                new Risk("支付渠道单一", 3, 5, "双渠道熔断路由（51-10）", "支付组"),
                new Risk("无全链路压测", 4, 3, "季度压测（56-02）", "平台组")));
        risks.sort((a, b) -> b.score() - a.score());
        for (Risk r : risks) {
            System.out.printf("  风险=%2d %-14s 缓解=%-24s owner=%s%n",
                    r.score(), r.desc(), r.mitigation(), r.owner());
        }
        System.out.println("  分级驱动投入：高分优先；清单季度评审滚动更新");
    }
}

