package com.heima.ch56;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

// ==================== 示例代码 ====================

public class DependencyGovernance {
    record Dependency(String name, boolean strong, String fallback, boolean rehearsed) {
    }

    static void audit() {
        System.out.println("【订单服务的依赖清单审计】");
        List<Dependency> deps = List.of(
                new Dependency("库存服务", true, "无（强依赖：本地缓存短时兜底）", true),
                new Dependency("营销服务", false, "不用券下单（降级开关）", true),
                new Dependency("推荐服务", false, "返回默认位（占位数据）", false),
                new Dependency("短信服务", false, "队列缓冲延发", true));
        for (Dependency d : deps) {
            System.out.printf("  %-8s %s依赖  降级=%-24s 演练=%s%n",
                    d.name(), d.strong() ? "强" : "弱", d.fallback(),
                    d.rehearsed() ? "✓" : "未演练");
        }
        System.out.println();
        System.out.println("  审计结论：推荐服务降级未演练 -> 进季度演练计划（56-06）");
        System.out.println("  健康度：强依赖必须容灾投入；弱依赖必须有演练过的降级");
    }

    public static void main(String[] args) {
        audit();
    }
}

