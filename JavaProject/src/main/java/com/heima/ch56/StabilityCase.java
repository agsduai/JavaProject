package com.heima.ch56;

import java.util.ArrayList;
import java.util.List;

// ==================== 示例代码 ====================

public class StabilityCase {
    record Phase(String day, String action, String output) {
    }

    static void closedLoop() {
        System.out.println("【大促稳定性闭环（复盘视角）】");
        List<Phase> ps = List.of(
                new Phase("T-30", "容量核算：峰值 ×3 -> 卡数重算（48-06）", "扩容 12->18 卡"),
                new Phase("T-21", "全链路压测（56-02）", "发现 MQ 瓶颈 -> 分区扩容"),
                new Phase("T-14", "瓶颈治理 + 预案更新（56-04）", "新增预案：MQ 积压自动扩容"),
                new Phase("T-7", "演练三项（56-06）", "全部通过 + 1 缺陷闭环"),
                new Phase("T-1", "冻结 + 值守就位（56-05）", "作战手册确认"),
                new Phase("T0", "峰值水位 66%，限流预案自动触发", "无人工介入"),
                new Phase("T+1", "复盘（42-11）", "2 改进项：公式修正/监控补盲"));
        for (Phase p : ps) {
            System.out.printf("  %-5s %-32s %s%n", p.day(), p.action(), p.output());
        }
        System.out.println();
        System.out.println("  闭环检验：改进项是否落进了下一次的容量公式与预案库 —— 循环即体系");
    }

    public static void main(String[] args) {
        closedLoop();
    }
}

