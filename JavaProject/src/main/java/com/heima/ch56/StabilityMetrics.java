package com.heima.ch56;

import java.util.LinkedHashMap;
import java.util.Map;

// ==================== 示例代码 ====================

public class StabilityMetrics {
    static void dashboard() {
        System.out.println("【稳定性月度看板】");
        Map<String, String> m = new LinkedHashMap<>();
        m.put("P1 事故", "0 次（MTTR 32min）");
        m.put("变更故障率", "6%（DORA 参考线 <15%）");
        m.put("演练覆盖率", "核心预案 85%（目标 90%）");
        m.put("错误预算", "已消耗 42%（健康）");
        m.put("缺陷闭环率", "78%（目标 90%，2 项逾期）");
        m.forEach((k, v) -> System.out.printf("  %-8s %s%n", k, v));
        System.out.println();
        System.out.println("  趋势比单点重要：连续三个月对比，任何指标连续劣化即立项");
    }

    public static void main(String[] args) {
        dashboard();
    }
}

