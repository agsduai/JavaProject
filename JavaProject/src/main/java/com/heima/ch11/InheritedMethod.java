package com.heima.ch11;

// ==================== 示例代码 ====================

public class InheritedMethod {
    public static void main(String[] args) {
        InheritedMethodDog d = new InheritedMethodDog();
        d.eat(); // 子类重写了父类方法，就近原则执行子类的版本
    }
}

class InheritedMethodAnimal {
    public void eat() {
        System.out.println("吃东西");
    }
}

class InheritedMethodDog extends InheritedMethodAnimal {
    // 方法重写：方法声明与父类完全一致，方法体改成子类需要的逻辑
    @Override
    public void eat() {
        System.out.println("狗吃骨头");
    }
}

