package com.heima.ch11;

// ==================== 示例代码 ====================

class MemberInnerClassOuterDemo {
    private int num = 10;           // 外部类私有成员
    private Inner in = new Inner(); // 外部类的成员：内部类对象

    // 非静态成员内部类
    public class Inner {
        public void show() {
            // 直接访问外部类的私有成员
            System.out.println("内部类访问外部类私有变量：" + num);
        }
    }

    // 外部类公有方法：把内部类的功能对外暴露
    public void useInner() {
        System.out.println("外部类使用内部类对象：");
        in.show(); // 内部类对象已经是外部类的成员，直接使用
    }
}

public class MemberInnerClass {
    public static void main(String[] args) {
        // 创建内部类对象的格式：new 外部类名().new 内部类名()
        MemberInnerClassOuterDemo.Inner oi = new MemberInnerClassOuterDemo().new Inner();
        oi.show();

        // 通过外部类方法间接使用内部类
        new MemberInnerClassOuterDemo().useInner();
    }
}

