package com.heima.ch11;

// ==================== 示例代码 ====================

// 外部类
class InnerClassIntroOuterDemo {
    private int num = 10; // 外部类私有成员

    // 成员内部类：定义在外部类的成员位置
    public class Inner {
        public void show() {
            // 内部类可以直接访问外部类的成员，包括私有的
            System.out.println("内部类访问外部类私有变量 num：" + num);
        }
    }

    // 外部类方法：访问内部类成员，必须先创建内部类对象
    public void method() {
        Inner i = new Inner();
        i.show();
    }
}

public class InnerClassIntro {
    public static void main(String[] args) {
        InnerClassIntroOuterDemo o = new InnerClassIntroOuterDemo();
        o.method(); // 通过外部类的方法间接使用内部类

        // 测试类中也可以直接创建内部类对象（格式后面课程细讲）
        InnerClassIntroOuterDemo.Inner i = new InnerClassIntroOuterDemo().new Inner();
        i.show();
    }
}

