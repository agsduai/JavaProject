package com.heima.practice.core;

// ==================== 示例代码 ====================

public class BankTransferTask {
    static int counter = 0;

    static void unsafe() throws Exception {
        counter = 0;
        Thread[] ts = new Thread[10];
        for (int i = 0; i < ts.length; i++) {
            ts[i] = new Thread(() -> {
                for (int j = 0; j < 1000; j++) {
                    counter++;          // 读-改-写 非原子
                }
            });
            ts[i].start();
        }
        for (Thread t : ts) {
            t.join();
        }
        System.out.printf("  期望 10000，实际 %d（丢失更新）%n", counter);
    }

    public static void main(String[] args) throws Exception {
        unsafe();
    }
}

