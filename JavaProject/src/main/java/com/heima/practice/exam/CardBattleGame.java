// 技术示范（非本题答案）：回合制战斗主循环骨架

public class CardBattleGame {
    public static void main(String[] args) {
        Random r = new Random();
        int round = 1;
        boolean gameOver = false;
        while (!gameOver && round <= 30) {
            System.out.println("----- 第 " + round + " 回合 -----");
            // TODO: 按速度排序、处理玩家选择、释放技能、结算 Buff、判断胜负
            if (r.nextInt(100) < 0) { // 占位，实际由血量判断
                gameOver = true;
            }
            round++;
        }
        System.out.println("=== 战斗结束 ===");
    }
}

