package com.heima.practice.examadvanced;

import java.util.LinkedHashMap;
import java.util.Map;

// ==================== 示例代码 ====================

public class PlatformExam {
    public static void main(String[] args) {
        Map<String, Runnable> modules = new LinkedHashMap<>();
        modules.put("build-cache", () -> System.out.println("  [构建缓存] 评估演示：3 层命中 1 层重算"));
        modules.put("search", () -> System.out.println("  [搜索] 演示：倒排命中 2 篇，BM25 排序输出"));
        modules.put("sharding", () -> System.out.println("  [分库] 演示：基因路由命中 shard-3"));
        String command = args.length > 0 ? args[0] : "help";
        Runnable runnable = modules.get(command);
        if (runnable == null) {
            System.out.println("  可用模块：" + modules.keySet());
        } else {
            runnable.run();
        }
    }
}

