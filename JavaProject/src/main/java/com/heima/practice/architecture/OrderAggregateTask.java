package com.heima.practice.architecture;

// ==================== 示例代码 ====================

public class OrderAggregateTask {
    static long balance = 10_000;      // 分
    static final long MIN = 0;

    static synchronized boolean withdraw(long amount) {
        if (balance - amount < MIN) {
            return false;               // 不变量：余额永不低于 0
        }
        balance -= amount;
        return true;
    }

    public static void main(String[] args) throws Exception {
        Thread[] ts = new Thread[8];
        for (int i = 0; i < ts.length; i++) {
            ts[i] = new Thread(() -> withdraw(2000));
            ts[i].start();
        }
        for (Thread t : ts) {
            t.join();
        }
        System.out.printf("  并发扣款后余额 = %d 分（不变量保持：>= 0）%n", balance);
    }
}

