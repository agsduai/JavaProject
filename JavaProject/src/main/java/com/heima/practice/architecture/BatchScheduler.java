package com.heima.practice.architecture;

import java.util.ArrayList;
import java.util.List;

// ==================== 示例代码 ====================

public class BatchScheduler {
    public static void main(String[] args) {
        List<Integer> batch = new ArrayList<>(List.of(40, 380, 120, 50));
        int step = 0;
        while (!batch.isEmpty()) {
            step++;
            batch.replaceAll(remaining -> remaining - 1);
            batch.removeIf(r -> r <= 0);
        }
        System.out.printf("  static：批内最长 %d token 决定总步数 %d%n", 380, step);
        System.out.println("  短请求的等待步 = 空转（continuous 会即时补位）");
    }
}

