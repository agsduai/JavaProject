package com.heima.practice.architecture;

// ==================== 示例代码 ====================

public class OutboxTask {
    enum State {
        PENDING, SENT, DEAD
    }

    static String advance(State s, boolean deliverOk, int retry) {
        if (s == State.PENDING) {
            return deliverOk ? State.SENT.name()
                    : (retry >= 5 ? State.DEAD.name() : State.PENDING.name());
        }
        return s.name();
    }

    public static void main(String[] args) {
        State s = State.PENDING;
        for (int retry = 1; retry <= 6; retry++) {
            s = State.valueOf(advance(s, false, retry));
            System.out.printf("  投递#%d 失败 -> 状态 %s%n", retry, s);
        }
        System.out.println("  进入 DEAD -> 告警 + 人工介入（事件不静默丢失）");
    }
}

