package com.heima.practice.architecture;

import java.util.ArrayList;
import java.util.List;

// ==================== 示例代码 ====================

public class ChaosExperiment {
    public static void main(String[] args) {
        List<Double> successRates = List.of(0.995, 0.993, 0.985, 0.972, 0.951);
        double threshold = 0.97;
        for (int min = 0; min < successRates.size(); min++) {
            double r = successRates.get(min);
            System.out.printf("  min%d 成功率 %.1f%%%n", min, r * 100);
            if (r < threshold) {
                System.out.printf("  触发自动中止（阈值 %.0f%%），回收注入%n", threshold * 100);
                break;
            }
        }
    }
}

