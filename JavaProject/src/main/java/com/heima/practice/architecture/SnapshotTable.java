package com.heima.practice.architecture;

// ==================== 示例代码 ====================

public class SnapshotTable {
    static long current = 0;

    static synchronized boolean cas(long expect, long update) {
        if (current != expect) {
            return false;
        }
        current = update;
        return true;
    }

    public static void main(String[] args) {
        long base = current;
        boolean a = cas(base, base + 1);      // A 先提交成功
        boolean b = cas(base, base + 1);      // B 基于旧快照 -> 失败重试
        System.out.printf("  A 提交=%b  B 提交=%b  当前=%d%n", a, b, current);
        System.out.println("  B 应基于最新快照重算后重新 CAS —— 乐观并发语义");
    }
}

