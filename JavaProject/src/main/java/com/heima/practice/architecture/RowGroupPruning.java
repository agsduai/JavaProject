package com.heima.practice.architecture;

// ==================== 示例代码 ====================

public class RowGroupPruning {
    record Group(int id, int min, int max, int bytes) {
    }

    static boolean mayMatch(Group g, int qMin, int qMax) {
        return g.min <= qMax && g.max >= qMin;    // 区间相交判定
    }

    public static void main(String[] args) {
        Group[] groups = {new Group(1, 0, 100, 128), new Group(2, 200, 300, 128)};
        int qMin = 150, qMax = 250;
        for (Group g : groups) {
            System.out.printf("  RG%d [%d,%d] -> %s%n", g.id(), g.min(), g.max(),
                    mayMatch(g, qMin, qMax) ? "读取" : "跳过");
        }
    }
}

