package com.heima.practice.architecture;

import java.util.HashMap;
import java.util.Map;

// ==================== 示例代码 ====================

public class CanaryRouter {
    static final Map<String, String> sticky = new HashMap<>();

    static String route(String userId, String defaultVersion) {
        return sticky.computeIfAbsent(userId, k -> defaultVersion);
    }

    public static void main(String[] args) {
        for (int i = 0; i < 3; i++) {
            System.out.println("  u1 第" + (i + 1) + " 次请求 -> " + route("u1", "v2"));
        }
        System.out.println("  同用户恒定同版本 —— 灰度体验一致性的最低要求");
    }
}

