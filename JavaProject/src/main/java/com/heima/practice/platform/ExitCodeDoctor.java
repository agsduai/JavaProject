package com.heima.practice.platform;

import java.util.Map;

// ==================== 示例代码 ====================

public class ExitCodeDoctor {
    record Finding(String code, String meaning, String action) {
    }

    static final Map<String, Finding> TABLE = Map.of(
            "E-01", new Finding("E-01", "依赖连接超时", "检查下游健康与超时预算"),
            "E-02", new Finding("E-02", "配置缺失", "核对配置中心与启动参数"),
            "E-03", new Finding("E-03", "磁盘写满", "清理并加水位告警"));

    public static void main(String[] args) {
        for (String code : new String[]{"E-02", "E-01", "E-99"}) {
            Finding f = TABLE.get(code);
            System.out.printf("  %s -> %s%n    动作：%s%n", code,
                    f == null ? "未知编码，按通用排查（日志+依赖）" : f.meaning(),
                    f == null ? "收集上下文升级处理" : f.action());
        }
    }
}

