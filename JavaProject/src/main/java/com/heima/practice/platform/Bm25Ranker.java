package com.heima.practice.platform;

import java.util.LinkedHashMap;
import java.util.Map;

// ==================== 示例代码 ====================

public class Bm25Ranker {
    record Explain(String item, double value, String note) {
    }

    public static void main(String[] args) {
        Map<String, Double> factors = new LinkedHashMap<>();
        factors.put("流行度加成", 1.2);
        factors.put("新鲜度衰减", 0.85);
        factors.put("库存惩罚", 0.95);
        double score = 10;
        for (Map.Entry<String, Double> e : factors.entrySet()) {
            score *= e.getValue();
            System.out.printf("  %-8s ×%.2f -> 累计 %.3f%n", e.getKey(), e.getValue(), score);
        }
        System.out.println("  explain 思想：每一项可单独核对，排序争议不再靠猜");
    }
}

