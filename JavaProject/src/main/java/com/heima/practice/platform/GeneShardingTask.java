package com.heima.practice.platform;

// ==================== 示例代码 ====================

public class GeneShardingTask {
    // 32 位：8 位类型 | 12 位序号 | 12 位哈希
    static long encode(int type, int seq, int hash) {
        return ((long) (type & 0xFF) << 24) | ((seq & 0xFFF) << 12) | (hash & 0xFFF);
    }

    static int type(long v) {
        return (int) ((v >>> 24) & 0xFF);
    }

    public static void main(String[] args) {
        long v = encode(7, 3000, 0xAB1);
        System.out.printf("  编码=%d 反解类型=%d（应为 7）%n", v, type(v));
    }
}

