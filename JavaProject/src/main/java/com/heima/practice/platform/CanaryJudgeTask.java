package com.heima.practice.platform;

// ==================== 示例代码 ====================

public class CanaryJudgeTask {
    static String judge(double baseline, double current) {
        double delta = current - baseline;
        if (delta > 0.10) {
            return "ROLLBACK";
        }
        if (delta > 0.05) {
            return "ALERT-STOP";
        }
        if (delta > 0.02) {
            return "PAUSE";
        }
        return "PROCEED";
    }

    public static void main(String[] args) {
        double base = 0.10;
        for (double cur : new double[]{0.11, 0.13, 0.16, 0.22}) {
            System.out.printf("  基线%.2f 当前%.2f -> %s%n", base, cur, judge(base, cur));
        }
    }
}

