package com.heima.practice.platform;

// ==================== 示例代码 ====================

public class SnowflakeTask {
    static long last = 1000;

    static long next(long wallNow) {
        long now = Math.max(wallNow, last);   // 回拨吸收：永不后退
        last = now + 1;
        return now;
    }

    public static void main(String[] args) {
        System.out.println("  正常推进：" + next(1005) + " " + next(1006));
        System.out.println("  时钟回拨到 1003：" + next(1003) + "（仍单调递增）");
    }
}

