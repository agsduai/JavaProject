package com.heima.practice.deepdive;

import java.security.SecureRandom;
import java.util.Base64;

// ==================== 示例代码 ====================

public class SaltHashTask {
    public static void main(String[] args) {
        SecureRandom random = new SecureRandom();
        byte[] salt1 = new byte[16], salt2 = new byte[16];
        random.nextBytes(salt1);
        random.nextBytes(salt2);
        System.out.printf("  同一密码 盐1=%s%n", Base64.getEncoder().encodeToString(salt1));
        System.out.printf("           盐2=%s%n", Base64.getEncoder().encodeToString(salt2));
        System.out.println("  随机盐让彩虹表失效：攻击者必须逐用户重算");
    }
}

