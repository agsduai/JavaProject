package com.heima.practice.deepdive;

import java.util.PriorityQueue;
import java.util.Random;

// ==================== 示例代码 ====================

public class TopKTask {
    public static void main(String[] args) {
        PriorityQueue<Long> heap = new PriorityQueue<>();     // 小顶堆
        Random r = new Random(42);
        int k = 5;
        for (int i = 0; i < 1_000_000; i++) {
            long v = r.nextLong(1_000_000);
            if (heap.size() < k) {
                heap.add(v);
            } else if (v > heap.peek()) {
                heap.poll();
                heap.add(v);
            }
        }
        System.out.println("  Top5 = " + heap);
        System.out.println("  内存 O(k) 不随 n 增长 —— 流式 TopK 的核心");
    }
}

