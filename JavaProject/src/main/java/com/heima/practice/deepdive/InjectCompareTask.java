package com.heima.practice.deepdive;

// ==================== 示例代码 ====================

public class InjectCompareTask {
    static boolean evalPatched(String input) {
        // 拼接版：input 直接进"条件文本"
        String condition = "name = '" + input + "'";
        System.out.println("  拼接后条件文本：" + condition);
        return condition.contains("' OR '") && input.toLowerCase().contains("or");
    }

    static boolean evalBound(String input) {
        // 绑定版：条件结构与值分离
        System.out.println("  绑定版：结构固定 name = ?，值=" + input + "（纯数据）");
        return "alice".equals(input);       // 值只参与比较
    }

    public static void main(String[] args) {
        String evil = "x' OR '1'='1";
        System.out.printf("  拼接版判定 %b（被注入）%n", evalPatched(evil));
        System.out.printf("  绑定版判定 %b（值是纯数据）%n", evalBound(evil));
    }
}

