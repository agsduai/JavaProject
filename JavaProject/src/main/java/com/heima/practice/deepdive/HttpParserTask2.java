package com.heima.practice.deepdive;

// ==================== 示例代码 ====================

public class HttpParserTask2 {
    public static void main(String[] args) {
        String line = "GET /search?q=java+http&page=2 HTTP/1.1";
        String[] parts = line.split(" ");
        String path = parts[1];
        String query = path.contains("?") ? path.substring(path.indexOf('?') + 1) : "";
        System.out.printf("  方法=%s 路径=%s 查询=%s 版本=%s%n",
                parts[0], path.split("\\?")[0], query.replace("+", " "), parts[2]);
    }
}

