package com.heima.practice.basic;

import java.util.Random;

// ==================== 示例代码 ====================

// 技术示范（非本题答案）：Fisher-Yates 洗牌
public class MemberCardShuffle {
    public static void main(String[] args) {
        int[] cards = {1, 2, 3, 4, 5};
        Random r = new Random();
        for (int i = cards.length - 1; i > 0; i--) {
            int j = r.nextInt(i + 1);
            int temp = cards[i];
            cards[i] = cards[j];
            cards[j] = temp;
        }
        for (int card : cards) {
            System.out.print(card + " ");
        }
    }
}

