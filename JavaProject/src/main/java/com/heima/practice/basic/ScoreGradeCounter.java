package com.heima.practice.basic;

import java.util.Scanner;

// ==================== 示例代码 ====================

// 技术示范（非本题答案）：-1 结束，非法成绩跳过
public class ScoreGradeCounter {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int validCount = 0;
        int sum = 0;
        while (true) {
            System.out.print("请输入成绩（-1 结束）：");
            int score = sc.nextInt();
            if (score == -1) {
                break;
            }
            if (score < 0 || score > 100) {
                System.out.println("无效成绩，已跳过");
                continue;
            }
            validCount++;
            sum += score;
        }
        System.out.println("有效人数：" + validCount + "，总分：" + sum);
        sc.close();
    }
}

