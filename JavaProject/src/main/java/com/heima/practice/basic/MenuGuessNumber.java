package com.heima.practice.basic;

import java.util.Scanner;

// ==================== 示例代码 ====================

// 技术示范（非本题答案）：菜单循环 + switch 分发
public class MenuGuessNumber {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        while (true) {
            System.out.println("1. 开始  2. 关于  0. 退出");
            int choice = sc.nextInt();
            switch (choice) {
                case 1:
                    System.out.println("开始游戏...");
                    break;
                case 2:
                    System.out.println("演示菜单");
                    break;
                case 0:
                    System.out.println("再见");
                    sc.close();
                    return;
                default:
                    System.out.println("选项无效");
            }
        }
    }
}

