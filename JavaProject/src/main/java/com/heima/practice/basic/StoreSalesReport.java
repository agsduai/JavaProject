package com.heima.practice.basic;

// ==================== 示例代码 ====================

// 技术示范（非本题答案）：数组遍历求最大值
public class StoreSalesReport {
    public static void main(String[] args) {
        double[] sales = {1200.5, 980.0, 1530.0, 0, 2010.5, 1760.0, 890.0};
        double max = sales[0];
        for (int i = 1; i < sales.length; i++) {
            if (sales[i] > max) {
                max = sales[i];
            }
        }
        System.out.println("最高销售额：" + max);
    }
}

