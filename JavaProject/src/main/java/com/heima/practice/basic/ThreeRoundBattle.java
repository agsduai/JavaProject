package com.heima.practice.basic;

import java.util.Random;

// ==================== 示例代码 ====================

// 技术示范（非本题答案）：随机伤害 + 循环扣血骨架
public class ThreeRoundBattle {
    public static void main(String[] args) {
        Random r = new Random();
        int playerHp = 100;
        int round = 1;
        while (playerHp > 0 && round <= 3) {
            int damage = r.nextInt(10) + 5; // 5~14
            System.out.println("第 " + round + " 回合，受到伤害：" + damage);
            playerHp -= damage;
            round++;
        }
        System.out.println("剩余血量：" + Math.max(playerHp, 0));
    }
}

