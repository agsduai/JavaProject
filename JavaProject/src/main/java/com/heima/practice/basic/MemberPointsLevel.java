// 技术示范（非本题答案）：三元运算符、短路运算与强制转换
public class MemberPointsLevel {
    public static void main(String[] args) {
        double amount = 268.0;
        boolean vip = true;
        int times = 3;

        int base = (int) (vip ? amount * 1.5 : amount);
        int extra = times >= 3 ? 100 : 0;
        int points = base + extra;

        boolean freeShipping = (vip || amount >= 199) && amount > 0;
        System.out.println("积分：" + points);
        System.out.println("免运费：" + freeShipping);
    }
}

