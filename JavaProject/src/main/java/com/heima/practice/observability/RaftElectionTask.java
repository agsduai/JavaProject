package com.heima.practice.observability;

import java.util.Random;

// ==================== 示例代码 ====================

public class RaftElectionTask {
    public static void main(String[] args) {
        Random r = new Random(42);
        int splits = 0;
        for (int round = 0; round < 1000; round++) {
            int a = 150 + r.nextInt(150);
            int b = 150 + r.nextInt(150);
            if (a == b) {
                splits++;
            }
        }
        System.out.printf("  1000 轮中同时发起（会分裂）：%d 次，其余随机错开自然化解%n", splits);
    }
}

