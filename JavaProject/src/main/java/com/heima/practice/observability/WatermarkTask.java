package com.heima.practice.observability;

// ==================== 示例代码 ====================

public class WatermarkTask {
    static void trade(int toleranceSec, int disorderMax) {
        int correct = Math.min(disorderMax, toleranceSec);
        int delay = toleranceSec;
        System.out.printf("  容忍%ds：正确归属 ≤%ds（覆盖 %.0f%% 乱序），结果延迟 +%ds%n",
                toleranceSec, correct, correct * 100.0 / disorderMax, delay);
    }

    public static void main(String[] args) {
        for (int t : new int[]{0, 5, 10, 15}) {
            trade(t, 15);
        }
        System.out.println("  交换曲线：容忍度↑ -> 归属率↑、延迟↑ —— 无免费午餐");
    }
}

