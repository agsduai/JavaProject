package com.heima.practice.observability;

import java.util.ArrayList;
import java.util.List;

// ==================== 示例代码 ====================

public class WindowAggregator {
    public static void main(String[] args) {
        int[] events = {5, 35, 65, 95, 125};
        int size = 60, slide = 60;
        System.out.println("  事件\\窗口  [0,60) [60,120) [120,180)");
        for (int e : events) {
            StringBuilder row = new StringBuilder();
            for (int w = 0; w + size <= 180; w += slide) {
                boolean belong = e >= w && e < w + size;
                row.append(belong ? "   ✓  " : "   ·  ");
            }
            System.out.printf("  事件%3d    %s%n", e, row);
        }
        System.out.println("  滚动窗口每事件只属一行；滑动窗口会多归属");
    }
}

