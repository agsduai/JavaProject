package com.heima.practice.observability;

// ==================== 示例代码 ====================

public class FencingStore {
    static long maxSeq = 0;

    static boolean accept(long seq, String who) {
        if (seq <= maxSeq) {
            System.out.printf("  拒绝 %s seq=%d（当前最大 %d）%n", who, seq, maxSeq);
            return false;
        }
        maxSeq = seq;
        System.out.printf("  接受 %s seq=%d%n", who, seq);
        return true;
    }

    public static void main(String[] args) {
        accept(3, "B");
        accept(2, "A（旧持锁者）");
        accept(5, "C");
    }
}

