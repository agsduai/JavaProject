package com.heima.practice.framework;

import java.util.ArrayList;
import java.util.List;

// ==================== 示例代码 ====================

public class ValidationAggregator {
    record User(String name, int age) {
    }

    static List<String> validate(User u) {
        List<String> errors = new ArrayList<>();
        if (u.name() == null || u.name().isBlank()) {
            errors.add("name: 不能为空");
        }
        if (u.age() < 0 || u.age() > 150) {
            errors.add("age: 超出合理范围");
        }
        return errors;
    }

    public static void main(String[] args) {
        List<String> errs = validate(new User("", -1));
        System.out.println("  聚合错误：" + errs + "（一次性返回全部，而不是逐个试错）");
    }
}

