package com.heima.practice.framework;

// ==================== 示例代码 ====================

public class IsolationTask {
    static volatile int value = 100;
    static volatile boolean committed = false;

    public static void main(String[] args) throws Exception {
        Thread writer = new Thread(() -> {
            value = 50;                       // 未提交
            try {
                Thread.sleep(100);
            } catch (InterruptedException e) {
            }
            committed = true;                 // 提交
        });
        writer.start();
        Thread.sleep(50);                     // 读侧在提交前读
        System.out.printf("  读未提交视角读到 %d（committed=%b）-> %s%n",
                value, committed, committed ? "正常读" : "脏读！");
        writer.join();
        System.out.printf("  提交后读到 %d%n", value);
    }
}

