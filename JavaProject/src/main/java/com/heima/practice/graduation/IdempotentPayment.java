package com.heima.practice.graduation;

import java.util.concurrent.ConcurrentHashMap;

// ==================== 示例代码 ====================

public class IdempotentPayment {
    static final ConcurrentHashMap<String, String> seen = new ConcurrentHashMap<>();

    static String first(String key, String value) {
        return seen.putIfAbsent(key, value);   // 首次返回 null，重复返回旧值
    }

    public static void main(String[] args) {
        System.out.println("  首次：" + first("n-1", "processed"));
        System.out.println("  重复：" + first("n-1", "processed-again") + "（拿到首次结果，忽略新值）");
    }
}

