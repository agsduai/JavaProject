package com.heima.practice.graduation;

import java.util.List;

// ==================== 示例代码 ====================

public class DoubleEntryTask {
    record Entry(String account, boolean debit, long cents) {
    }

    static boolean balanced(List<Entry> entries) {
        long d = entries.stream().filter(e -> e.debit()).mapToLong(e -> e.cents()).sum();
        long c = entries.stream().filter(e -> !e.debit()).mapToLong(e -> e.cents()).sum();
        return d == c;
    }

    public static void main(String[] args) {
        var ok = List.of(new Entry("A", true, 100), new Entry("B", false, 100));
        var bad = List.of(new Entry("A", true, 100), new Entry("B", false, 90));
        System.out.printf("  正常分录平衡：%b%n", balanced(ok));
        System.out.printf("  方向搞反/金额错 平衡：%b（当场发现）%n", balanced(bad));
    }
}

