package com.heima.practice.graduation;

// ==================== 示例代码 ====================

public class CapacityEstimator {
    public static void main(String[] args) {
        long dau = 1_000_000;
        double reqPerUser = 10;
        double slot = 0.2;
        double peak = 3.0;
        long avgQps = Math.round(dau * reqPerUser / (86400 * slot));
        long peakQps = Math.round(avgQps * peak);
        System.out.printf("  平均 QPS=%d  峰值=%d（推导：日活×人均÷时段×因子）%n", avgQps, peakQps);
    }
}

