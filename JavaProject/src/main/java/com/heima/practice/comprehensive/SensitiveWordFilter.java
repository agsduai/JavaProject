// 技术示范（非本题答案）：统计子串出现次数
public class SensitiveWordFilter {
    public static void main(String[] args) {
        String text = "java 和 Java 都是 JAVA";
        String word = "Java";
        int count = 0;
        int index = 0;
        while ((index = text.indexOf(word, index)) != -1) {
            count++;
            index += word.length();
        }
        System.out.println(word + " 出现次数：" + count);
    }
}

