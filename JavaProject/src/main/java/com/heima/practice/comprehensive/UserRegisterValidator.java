// 技术示范（非本题答案）：统计字符串中的字母与数字
public class UserRegisterValidator {
    public static void main(String[] args) {
        String s = "abc123";
        boolean hasDigit = false;
        boolean hasLetter = false;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c >= '0' && c <= '9') {
                hasDigit = true;
            }
            if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')) {
                hasLetter = true;
            }
        }
        System.out.println("含数字：" + hasDigit + "，含字母：" + hasLetter);
    }
}

