// 技术示范（非本题答案）：用 == 与标识值观察引用
public class MethodArrayAnalysis {
    public static void main(String[] args) {
        int[] a = {1, 2, 3};
        int[] b = a;
        int[] c = new int[]{1, 2, 3};
        System.out.println("a 与 b 是否同一对象：" + (a == b));
        System.out.println("a 与 c 是否同一对象：" + (a == c));
        System.out.println("a 的标识：" + System.identityHashCode(a));
    }
}

