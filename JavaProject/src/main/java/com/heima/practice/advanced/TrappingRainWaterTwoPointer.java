// 技术示范（非本题答案）：双指针相向移动
public class TrappingRainWaterTwoPointer {
    public static void main(String[] args) {
        int[] arr = {1, 3, 2, 5, 4};
        int left = 0;
        int right = arr.length - 1;
        while (left < right) {
            if (arr[left] < arr[right]) {
                left++;
            } else {
                right--;
            }
        }
        System.out.println("相遇位置：" + left);
    }
}

