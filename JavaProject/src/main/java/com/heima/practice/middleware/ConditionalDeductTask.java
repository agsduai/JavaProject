package com.heima.practice.middleware;

// ==================== 示例代码 ====================

public class ConditionalDeductTask {
    static int stock = 50;
    static int success = 0, rejected = 0;

    static synchronized boolean deduct(int qty) {
        if (stock >= qty) {                 // 原子化后的 check-then-act
            stock -= qty;
            success++;
            return true;
        }
        rejected++;
        return false;
    }

    public static void main(String[] args) throws Exception {
        Thread[] ts = new Thread[200];
        for (int i = 0; i < ts.length; i++) {
            ts[i] = new Thread(() -> deduct(1));
            ts[i].start();
        }
        for (Thread t : ts) {
            t.join();
        }
        System.out.printf("  成功 %d / 拒绝 %d / 剩余库存 %d（恒等：%b）%n",
                success, rejected, stock, success == 50 && stock == 0);
    }
}

