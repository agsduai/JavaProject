package com.heima.practice.middleware;

// ==================== 示例代码 ====================

public class ConfigClientTask {
    static long local = 42;

    static void apply(long serverVersion, String value) {
        if (serverVersion <= local) {
            System.out.printf("  拒绝 v%d（本地 v%d）—— 防旧实例推送%n", serverVersion, local);
            return;
        }
        local = serverVersion;
        System.out.printf("  应用 v%d：%s%n", serverVersion, value);
    }

    public static void main(String[] args) {
        apply(43, "timeout=3000");
        apply(41, "timeout=1000");
        apply(44, "timeout=5000");
    }
}

