package com.heima.practice.middleware;

import java.util.LinkedHashMap;
import java.util.Map;

// ==================== 示例代码 ====================

public class HeartbeatRegistry {
    static final Map<String, Long> lastBeat = new LinkedHashMap<>();
    static final long TTL = 15000;

    static boolean alive(String instance, long now) {
        Long last = lastBeat.get(instance);
        return last != null && now - last <= TTL;
    }

    public static void main(String[] args) {
        lastBeat.put("i-1", 0L);
        lastBeat.put("i-2", 0L);
        System.out.println("  t=0    alive i-1=" + alive("i-1", 0) + " i-2=" + alive("i-2", 0));
        System.out.println("  t=16s  i-2 未续约 -> alive=" + alive("i-2", 16000) + "（剔除）");
        lastBeat.put("i-2", 16000L);
        System.out.println("  t=17s  i-2 复活续约 -> alive=" + alive("i-2", 17000));
    }
}

