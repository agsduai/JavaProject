package com.heima.practice.middleware;

// ==================== 示例代码 ====================

public class RetryDlqTask {
    public static void main(String[] args) {
        long delay = 1000;
        for (int attempt = 1; attempt <= 3; attempt++) {
            System.out.printf("  第 %d 次重试（延迟 %dms）%n", attempt, delay);
            delay *= 2;
        }
        System.out.println("  3 次后进死信 -> 告警 + 人工重放");
    }
}

