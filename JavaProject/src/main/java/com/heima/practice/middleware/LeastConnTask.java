package com.heima.practice.middleware;

import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.atomic.AtomicInteger;

// ==================== 示例代码 ====================

public class LeastConnTask {
    record Node(String name, AtomicInteger conn) {
    }

    public static void main(String[] args) {
        List<Node> nodes = List.of(new Node("n1", new AtomicInteger(5)),
                new Node("n2", new AtomicInteger(1)), new Node("n3", new AtomicInteger(3)));
        Node best = nodes.stream().min((a, b) -> Integer.compare(a.conn().get(), b.conn().get()))
                .orElseThrow();
        System.out.printf("  最少连接路由 -> %s（当前 %d 连接）%n", best.name(), best.conn().get());
    }
}

