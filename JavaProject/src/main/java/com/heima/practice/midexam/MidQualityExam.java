import java.util.ArrayList;
import java.util.List;

// ==================== 示例代码 ====================

public class MidQualityExam {
    public static void main(String[] args) {
        List<Long> costs = new ArrayList<>(List.of(20L, 25L, 30L, 28L, 22L, 90L));
        costs.sort(Long::compare);
        int n = costs.size();
        System.out.printf("  P50=%dms P90=%dms Max=%dms（样本 %d）%n",
                costs.get((int) (0.5 * n)), costs.get((int) (0.9 * n)), costs.get(n - 1), n);
    }
}

