package com.heima.ch02;

// ==================== 示例代码 ====================

public class OperatorPrecedence {
    public static void main(String[] args) {
        // 乘除模高于加减
        System.out.println(3 + 4 * 2);     // 11
        System.out.println((3 + 4) * 2);   // 14：小括号改变顺序
        System.out.println(5 % 2 * 3);     // 3：同级别从左到右
        // && 优先级高于 ||
        System.out.println(true || false && false);     // true：先算&&
        System.out.println((true || false) && false);   // false：加括号改变顺序
        // 关系高于逻辑
        int a = 10;
        int b = 5;
        System.out.println(a > b && b > 0);   // 先比较再逻辑与，true
        // 一元运算符优先级很高
        int c = 5;
        System.out.println(-c * 2 + 10);   // 0：先取负再乘2
    }
}

