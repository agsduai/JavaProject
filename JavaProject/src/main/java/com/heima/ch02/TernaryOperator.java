package com.heima.ch02;

// ==================== 示例代码 ====================

public class TernaryOperator {
    public static void main(String[] args) {
        // 三元运算符：关系表达式 ? 值1 : 值2
        int a = 25;
        int b = 31;
        // a > b 成立取a，不成立取b
        int max = a > b ? a : b;
        System.out.println("较大值：" + max);   // 31
        // 结果也可以直接打印
        System.out.println(a > 0 ? "正数" : "非正数");
        // 判断奇偶：余数为0是偶数
        System.out.println(a % 2 == 0 ? "偶数" : "奇数");
    }
}

