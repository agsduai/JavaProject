package com.heima.ch02;

// ==================== 示例代码 ====================

public class StringConcat {
    public static void main(String[] args) {
        // 字符串与其他类型拼接
        String name = "阿玮";
        int age = 18;
        System.out.println("我叫" + name + "，今年" + age + "岁");
        // 从左到右运算：先算数字加法，遇到字符串才开始拼接
        System.out.println(1 + 2 + "岁");    // 3岁
        System.out.println("岁" + 1 + 2);    // 岁12
        // 用空字符串让数字直接按字符串拼接
        System.out.println("" + 1 + 2);      // 12
        // 占位思路：固定文字 + 变量
        int price = 5;
        int count = 3;
        System.out.println("单价" + price + "元，共" + count + "件，总价" + price * count + "元");
    }
}

