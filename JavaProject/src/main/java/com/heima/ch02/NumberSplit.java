package com.heima.ch02;

// ==================== 示例代码 ====================

public class NumberSplit {
    public static void main(String[] args) {
        // 待拆分的三位数
        int num = 587;
        // 个位：对10取余
        int ge = num % 10;
        // 十位：先除以10去掉个位，再对10取余
        int shi = num / 10 % 10;
        // 百位：直接除以100
        int bai = num / 100;
        // 输出拆分结果
        System.out.println(num + "的个位：" + ge);
        System.out.println(num + "的十位：" + shi);
        System.out.println(num + "的百位：" + bai);
    }
}

