package com.heima.ch02;

// ==================== 示例代码 ====================

public class VariableNotes {
    public static void main(String[] args) {
        // 变量只能存一个值，新值覆盖旧值
        int score = 60;
        score = 95;
        System.out.println(score);   // 95
        // long装大数字要加L
        long bigNum = 10000000000L;
        System.out.println(bigNum);
        // float要加F，否则小数默认按double处理
        float price = 9.9F;
        System.out.println(price);
        // 变量必须先赋值再使用
        int count = 0;
        System.out.println(count);
        // 一行可以定义多个同类型变量（了解，不推荐）
        int x = 1, y = 2;
        System.out.println(x + y);
    }
}

