package com.heima.ch02;

// ==================== 示例代码 ====================

public class TypeConversion {
    public static void main(String[] args) {
        // 隐式转换：小范围 -> 大范围，自动完成
        int a = 10;
        long b = a;       // int自动提升为long
        double c = b;     // long自动提升为double
        System.out.println(b);
        System.out.println(c);
        // byte参与运算先提升为int
        byte d = 10;
        byte e = 20;
        int sum = d + e;  // 结果是int，不能直接赋给byte
        System.out.println(sum);
        // 强制转换：大范围 -> 小范围，必须写(类型)
        int f = (int) 3.99;    // 直接舍弃小数部分
        System.out.println(f); // 3
    }
}

