package com.heima.ch02;

// ==================== 示例代码 ====================

public class StreetFighter {
    public static void main(String[] args) {
        // 用变量保存格斗游戏《街头霸王》角色"隆"的信息
        String name = "隆";             // 角色姓名
        int hp = 300;                   // 血量
        int attack = 85;                // 攻击力
        int defense = 60;               // 防御力
        String skill = "波动拳";         // 必杀技名称
        boolean isUnlock = true;        // 是否已解锁
        // 拼接输出角色信息
        System.out.println("===== 角色信息 =====");
        System.out.println("姓名：" + name);
        System.out.println("血量：" + hp);
        System.out.println("攻击力：" + attack);
        System.out.println("防御力：" + defense);
        System.out.println("必杀技：" + skill);
        System.out.println("是否已解锁：" + isUnlock);
    }
}

