package com.heima.ch61;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

// ==================== 示例代码 ====================

public class MechanismBoundary {
    record Mechanism(String name, String timing, String record, String fit) {
    }

    static void compare() {
        System.out.println("【三种机制的定位】");
        List<Mechanism> ms = List.of(
                new Mechanism("MQ", "毫秒~秒级，事件驱动", "偏移量（可重放）",
                        "订单创建后加积分、支付成功通知履约"),
                new Mechanism("调度", "有明确执行时刻", "执行记录（可重跑）",
                        "每天 2 点对账、每小时报表"),
                new Mechanism("批处理", "跑一次处理海量", "作业/Stage 记录（59 章）",
                        "T+1 全量清洗、特征回填"));
        for (Mechanism m : ms) {
            System.out.printf("  %-6s 时机=%-20s 记录=%-26s 适合=%s%n",
                    m.name(), m.timing(), m.record(), m.fit());
        }
        System.out.println();
    }

    static void comboPattern() {
        System.out.println("【调度 + MQ 的组合：大促历史数据回刷】");
        List<String> flow = List.of(
                "1) 调度 02:00 触发 reflushJob（带日期参数）",
                "2) reflushJob 按分片查库，每片产出 10 万条消息到 MQ",
                "3) MQ 多消费者并行处理（43 章），自动扩缩",
                "4) 全部消费完成 -> 调度任务校验总数（对账）",
                "5) 有缺口 -> 按分片重跑该段（61-05 幂等）");
        flow.forEach(s -> System.out.println("  " + s));
        System.out.println("  分工：调度管时刻与重跑，MQ 管并行与削峰，批处理管海量扫描");
        System.out.println();
    }

    static void misuse() {
        System.out.println("【常见误用】");
        Map<String, String> cases = new LinkedHashMap<>();
        cases.put("MQ 做定时", "延迟消息精度低且无执行记录 -> 改用调度");
        cases.put("调度做实时", "秒级最小粒度 + 每次触发有开销 -> 改用 MQ");
        cases.put("高频小任务", "每小时 60 次 -> 合并为每分钟一次或批量");
        cases.forEach((k, v) -> System.out.printf("  %-10s %s%n", k, v));
    }

    public static void main(String[] args) {
        compare();
        comboPattern();
        misuse();
    }
}

