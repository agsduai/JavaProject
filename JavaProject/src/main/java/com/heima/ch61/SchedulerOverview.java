package com.heima.ch61;

import java.util.ArrayList;
import java.util.List;

// ==================== 示例代码 ====================

public class SchedulerOverview {
    record Capability(String name, String problem, String mechanism) {
    }

    static void gaps() {
        System.out.println("【单机 cron 的三个缺口】");
        String[][] rows = {
                {"高可用", "机器挂了任务丢失", "执行器集群 + 失败重派（61-02）"},
                {"分片", "单机跑不完大数据量", "任务分片并行（61-03）"},
                {"观测", "跑没跑没人知道", "执行历史 + 告警（61-09）"},
        };
        for (String[] r : rows) {
            System.out.printf("  %-6s 问题=%-16s 解法=%s%n", r[0], r[1], r[2]);
        }
        System.out.println();
    }

    static void capabilityMap() {
        System.out.println("【调度平台四能力】");
        List<Capability> caps = List.of(
                new Capability("注册发现", "任务散落各处", "任务定义集中存储 + 执行器心跳"),
                new Capability("触发分片", "何时跑/怎么并行", "cron/事件触发 + 分片广播"),
                new Capability("故障转移", "执行器宕机", "心跳超时摘除 + 任务重派"),
                new Capability("可观测", "跑没跑/慢不慢", "执行日志 + 成功率 + 耗时分布"));
        for (Capability c : caps) {
            System.out.printf("  %-6s %-14s %s%n", c.name(), c.problem(), c.mechanism());
        }
        System.out.println();
    }

    static void schedulerVsMq() {
        System.out.println("【调度 vs MQ 的边界】");
        String[][] rows = {
                {"每天 2 点对账", "调度", "需要保证某时刻执行一次"},
                {"订单创建后加积分", "MQ", "事件驱动，无需固定时刻"},
                {"分片导出千万订单", "调度（分片）", "批处理单元，可分片并行"},
                {"支付成功通知履约", "MQ", "实时事件，消费者可扩"},
        };
        for (String[] r : rows) {
            System.out.printf("  %-18s -> %-10s %s%n", r[0], r[1], r[2]);
        }
    }

    public static void main(String[] args) {
        gaps();
        capabilityMap();
        schedulerVsMq();
    }
}

