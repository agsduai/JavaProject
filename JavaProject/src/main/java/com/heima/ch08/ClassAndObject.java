package com.heima.ch08;

// ==================== 示例代码 ====================

// 类：描述手机这一类事物共同的特征（属性 + 行为）
class ClassAndObjectPhone {
    // 成员变量（属性）
    String brand; // 品牌
    double price; // 价格

    // 成员方法（行为）
    public void call() {
        System.out.println("用" + brand + "手机打电话");
    }

    public void playGame() {
        System.out.println("用" + brand + "手机玩游戏");
    }
}

// 测试类：创建对象并使用
public class ClassAndObject {
    public static void main(String[] args) {
        // 创建对象：类名 对象名 = new 类名();
        ClassAndObjectPhone p = new ClassAndObjectPhone();

        // 给成员变量赋值：对象名.成员变量
        p.brand = "华为";
        p.price = 6999.0;

        // 使用成员变量
        System.out.println(p.brand); // 华为
        System.out.println(p.price); // 6999.0

        // 调用成员方法：对象名.方法名()
        p.call();
        p.playGame();
    }
}

