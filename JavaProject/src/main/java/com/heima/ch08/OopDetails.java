package com.heima.ch08;

// ==================== 示例代码 ====================

// 描述类：学生
class OopDetailsStudent {
    String name;  // 不赋值时默认值是 null
    int age;      // 不赋值时默认值是 0
    double score; // 不赋值时默认值是 0.0
    boolean male; // 不赋值时默认值是 false

    public void study() {
        System.out.println(name + "正在学习");
    }
}

// 测试类
public class OopDetails {
    public static void main(String[] args) {
        OopDetailsStudent stu = new OopDetailsStudent();
        // 没有赋值，直接打印成员变量，输出各自的默认值
        System.out.println(stu.name);  // null
        System.out.println(stu.age);   // 0
        System.out.println(stu.score); // 0.0
        System.out.println(stu.male);  // false

        // 赋值后再调用方法
        stu.name = "阿玮";
        stu.study();
    }
}

