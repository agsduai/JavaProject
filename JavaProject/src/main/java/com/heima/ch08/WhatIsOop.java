package com.heima.ch08;

// ==================== 示例代码 ====================

// 对比：面向过程 vs 面向对象（任务：把数组排序并打印）
public class WhatIsOop {
    public static void main(String[] args) {
        int[] arr = {5, 2, 8, 1};

        // 面向过程：每一步都自己写，关注"怎么做"
        // 步骤1：冒泡排序
        for (int i = 0; i < arr.length - 1; i++) {
            for (int j = 0; j < arr.length - 1 - i; j++) {
                if (arr[j] > arr[j + 1]) {
                    int temp = arr[j];
                    arr[j] = arr[j + 1];
                    arr[j + 1] = temp;
                }
            }
        }
        // 步骤2：自己遍历打印
        for (int i = 0; i < arr.length; i++) {
            System.out.print(arr[i] + " ");
        }
        System.out.println();

        // 面向对象：找 JDK 现成的"对象"帮忙，关注"谁来帮我做"
        // Arrays 是 JDK 提供的数组工具类，排序和转字符串都让它来做
        int[] arr2 = {5, 2, 8, 1};
        java.util.Arrays.sort(arr2);
        System.out.println(java.util.Arrays.toString(arr2));
    }
}

