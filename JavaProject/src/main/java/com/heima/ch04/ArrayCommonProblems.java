package com.heima.ch04;

// ==================== 示例代码 ====================

public class ArrayCommonProblems {
    public static void main(String[] args) {
        // 问题一：空指针异常
        int[] arr1 = null;
        // System.out.println(arr1[0]); // NullPointerException

        // 问题二：索引越界异常
        int[] arr2 = {1, 2, 3};
        // System.out.println(arr2[3]); // ArrayIndexOutOfBoundsException

        // 正确姿势：先判断引用是否为 null
        if (arr1 != null) {
            System.out.println(arr1[0]);
        } else {
            System.out.println("arr1 没有指向任何数组");
        }

        // 正确姿势：访问前核对索引范围
        int index = 2;
        if (index >= 0 && index < arr2.length) {
            System.out.println(arr2[index]);
        }
    }
}

