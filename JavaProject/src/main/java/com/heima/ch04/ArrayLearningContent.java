package com.heima.ch04;

// ==================== 示例代码 ====================

public class ArrayLearningContent {
    public static void main(String[] args) {
        // 本章路线：初始化 -> 访问 -> 遍历 -> 综合练习
        int[] arr = {5, 12, 8, 20, 3};

        // 第一站：按索引访问元素
        System.out.println("第 3 个元素：" + arr[2]);

        // 第二站：用 for 循环遍历数组
        for (int i = 0; i < arr.length; i++) {
            System.out.println("索引 " + i + " -> " + arr[i]);
        }

        // 第三站：综合练习中会实现的功能（求最大值）先睹为快
        int max = arr[0];
        for (int i = 1; i < arr.length; i++) {
            if (arr[i] > max) {
                max = arr[i];
            }
        }
        System.out.println("最大值：" + max);
    }
}

