package com.heima.ch04;

// ==================== 示例代码 ====================

public class SearchData {
    public static void main(String[] args) {
        // 需求：查找 46 在数组中的索引，不存在则输出 -1
        int[] arr = {19, 28, 37, 46, 50};
        int target = 46;

        // index 初始为 -1，表示"还没找到"
        int index = -1;
        for (int i = 0; i < arr.length; i++) {
            if (arr[i] == target) {
                index = i;
                break; // 找到就结束，无需继续比较
            }
        }

        if (index == -1) {
            System.out.println(target + " 不存在于数组中，返回 " + index);
        } else {
            System.out.println(target + " 的索引是：" + index);
        }
    }
}

