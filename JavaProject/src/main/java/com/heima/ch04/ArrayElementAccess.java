package com.heima.ch04;

// ==================== 示例代码 ====================

public class ArrayElementAccess {
    public static void main(String[] args) {
        int[] arr = {10, 20, 30, 40};

        // 索引范围：0 ~ length - 1
        System.out.println(arr[0]); // 10
        System.out.println(arr[3]); // 40

        // 通过索引修改元素
        arr[1] = 200;
        System.out.println(arr[1]); // 200

        // length 是属性，直接使用，不加括号
        System.out.println("长度：" + arr.length);

        // 下面这行越界了，取消注释会报 ArrayIndexOutOfBoundsException
        // System.out.println(arr[4]);
    }
}

