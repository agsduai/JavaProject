package com.heima.ch04;

// ==================== 示例代码 ====================

public class ArrayMax {
    public static void main(String[] args) {
        // 需求：找出数组中的最大值
        int[] arr = {33, 5, 22, 44, 55};

        // 先假设第 0 个元素是最大值（擂主）
        int max = arr[0];

        // 从索引 1 开始逐个挑战擂主
        for (int i = 1; i < arr.length; i++) {
            if (arr[i] > max) {
                max = arr[i]; // 更大的元素成为新擂主
            }
        }

        System.out.println("最大值是：" + max); // 55
    }
}

