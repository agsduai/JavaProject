package com.heima.ch07;

// ==================== 示例代码 ====================

public class TrappingRainWater {
    public static void main(String[] args) {
        int[] height = {4, 2, 0, 3, 2, 5};
        System.out.println("能接住的雨水总量：" + trap(height));
        // 输出：能接住的雨水总量：9

        /*
         * 各位置的接水量（min(左最大,右最大) - 自身）：
         * 高度  : 4  2  0  3  2  5
         * 左最大: 4  4  4  4  4  5
         * 右最大: 5  5  5  5  5  5
         * 存水  : 0  2  4  1  2  0   合计 = 9
         */
    }

    // 按位置计算每个格子能存多少水，再累加
    public static int trap(int[] height) {
        int n = height.length;
        int[] leftMax = new int[n];  // leftMax[i]：i 及其左侧最高的柱子
        int[] rightMax = new int[n]; // rightMax[i]：i 及其右侧最高的柱子

        leftMax[0] = height[0];
        for (int i = 1; i < n; i++) {
            leftMax[i] = Math.max(leftMax[i - 1], height[i]); // 从左往右推
        }
        rightMax[n - 1] = height[n - 1];
        for (int i = n - 2; i >= 0; i--) {
            rightMax[i] = Math.max(rightMax[i + 1], height[i]); // 从右往左推
        }

        int water = 0;
        for (int i = 0; i < n; i++) {
            // 水位由两侧较矮的一侧决定，减去自身高度就是这一格的存水
            water += Math.min(leftMax[i], rightMax[i]) - height[i];
        }
        return water;
    }
}

