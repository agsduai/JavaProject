package com.heima.ch07;

import java.util.ArrayList;
import java.util.Random;

// ==================== 示例代码 ====================

public class RedPacket {
    public static void main(String[] args) {
        int total = 10000; // 总金额，单位：分（100 元）
        int size = 3;      // 抢红包的人数
        ArrayList<Integer> packets = new ArrayList<>();
        Random r = new Random();

        // 前面 size-1 人每人随机抢一次（二倍均值法）
        for (int i = 0; i < size - 1; i++) {
            int remainPeople = size - i;          // 还没抢的人数
            int bound = total / remainPeople * 2; // 随机上限 = 剩余金额 ÷ 剩余人数 × 2
            int money = r.nextInt(bound - 1) + 1; // 至少抢到 1 分（0.01 元）
            packets.add(money);
            total -= money; // 抢走的部分从总额中扣除
        }
        // 最后一个人拿走剩余全部，总额不变
        packets.add(total);

        System.out.println("手气红包分配结果（单位：元）：");
        for (int i = 0; i < packets.size(); i++) {
            System.out.println("第" + (i + 1) + "个人抢到：" + packets.get(i) / 100.0);
        }
        // 输出示例（每次运行随机）：
        // 第1个人抢到：45.32
        // 第2个人抢到：37.86
        // 第3个人抢到：16.82
    }
}

