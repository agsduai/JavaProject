package com.heima.ch07;

// ==================== 示例代码 ====================

public class MultiDataStatistics {
    public static void main(String[] args) {
        int[] scores = {88, 45, 92, 67, 59, 73};

        int sum = 0;              // 总和
        int max = scores[0];      // 最大值：初值取第一个元素
        int min = scores[0];      // 最小值：同上，别用 0
        int passCount = 0;        // 及格（>=60）人数

        for (int i = 0; i < scores.length; i++) {
            sum += scores[i];                       // 累加求和
            if (scores[i] > max) max = scores[i];   // 打擂台更新最大值
            if (scores[i] < min) min = scores[i];   // 打擂台更新最小值
            if (scores[i] >= 60) passCount++;       // 条件统计
        }

        System.out.println("总分：" + sum);                       // 424
        System.out.println("平均分：" + (double) sum / scores.length); // 70.666...
        System.out.println("最高分：" + max);                     // 92
        System.out.println("最低分：" + min);                     // 45
        System.out.println("及格人数：" + passCount);             // 4
    }
}

