package com.heima.ch68;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

// ==================== 示例代码 ====================

public class PrivacyOverview {
    record Principle(String name, String requirement, String technicalControl) {
    }

    static void principles() {
        System.out.println("【五项原则与技术落地】");
        List<Principle> ps = List.of(
                new Principle("最小必要", "只采集业务必需字段", "接口参数白名单 + 采集评审"),
                new Principle("目的限定", "用途不能挪用", "数据标签（用途）+ 使用审批"),
                new Principle("默认保护", "默认脱敏/不采集", "字段级默认掩码（68-03）"),
                new Principle("全生命周期", "采/传/存/用/享/销", "各阶段控制点清单"),
                new Principle("可问责", "每步可追溯", "访问审计 + 操作留痕（68-09）"));
        for (Principle p : ps) {
            System.out.printf("  %-8s %-26s %s%n", p.name(), p.requirement(), p.technicalControl());
        }
        System.out.println();
    }

    static void lifecycle() {
        System.out.println("【全生命周期的控制点】");
        Map<String, String> stages = new LinkedHashMap<>();
        stages.put("采集", "最小必要 + 告知同意 + 分类分级（68-02）");
        stages.put("传输", "TLS（35-07）+ 敏感字段额外加密");
        stages.put("存储", "静态加密 + 密钥管理（68-04）+ 保留期（68-10）");
        stages.put("使用", "行列级权限（68-05）+ 脱敏视图（68-03）");
        stages.put("共享", "出域审批 + 隐私计算（68-07/08）+ 不出境（68-06）");
        stages.put("销毁", "到期删除 + 删除凭证（68-10）");
        stages.forEach((k, v) -> System.out.printf("  %-4s %s%n", k, v));
        System.out.println();
    }

    static void privacyVsSecurity() {
        System.out.println("【隐私与安全的区别】");
        String[][] rows = {
                {"威胁来源", "外部攻击者", "内部越权/超范围使用"},
                {"目标", "不泄露", "合法使用"},
                {"典型手段", "鉴权/注入防护/加密（36 章）", "分级/脱敏/权限/审计（本章）"},
                {"共同点", "加密、权限、审计都用", "加密、权限、审计都用"},
        };
        for (String[] r : rows) {
            System.out.printf("  %-8s 安全=%-28s 隐私=%s%n", r[0], r[1], r[2]);
        }
    }

    public static void main(String[] args) {
        principles();
        lifecycle();
        privacyVsSecurity();
    }
}

