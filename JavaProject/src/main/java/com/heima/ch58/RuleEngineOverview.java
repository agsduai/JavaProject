package com.heima.ch58;

import java.util.List;

// ==================== 示例代码 ====================

public class RuleEngineOverview {
    record Rule(String id, String condition, String action, int priority) {
    }

    /** 三种形态的对比：硬编码 / 配置化 / 平台化 */
    static void evolution() {
        System.out.println("【规则表达的三代形态】");
        String[][] rows = {
                {"硬编码 if-else", "改规则 = 改代码 + 发布", "稳定规则"},
                {"配置化规则表", "改规则 = 改配置 + 热更", "高频变化的业务规则"},
                {"专业规则引擎", "RETE/规则网 + 事实推理", "数百条互相关联的规则"},
        };
        for (String[] r : rows) {
            System.out.printf("  %-16s %-26s %s%n", r[0], r[1], r[2]);
        }
        System.out.println();
    }

    static void anatomy() {
        System.out.println("【一条风控规则的完整定义】");
        List<Rule> rules = List.of(
                new Rule("R-001", "amount > 500000 && deviceAge < 1", "BLOCK", 100),
                new Rule("R-002", "amount > 100000 && hour >= 0 && hour < 6", "CHALLENGE", 80),
                new Rule("R-003", "userLevel == NEW && amount > 50000", "CHALLENGE", 60),
                new Rule("R-004", "always", "ALLOW", 0));
        for (Rule r : rules) {
            System.out.printf("  %-6s 优先级%-4d 条件=[%s] -> %s%n",
                    r.id(), r.priority(), r.condition(), r.action());
        }
        System.out.println("  要素齐全：条件/动作/优先级/元数据（id 即审计锚点）");
    }

    public static void main(String[] args) {
        evolution();
        anatomy();
        System.out.println("  判据：规则年变更次数 > 10 次才值得平台化");
    }
}

