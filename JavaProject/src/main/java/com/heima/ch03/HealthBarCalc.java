package com.heima.ch03;

// ==================== 示例代码 ====================

public class HealthBarCalc {
    public static void main(String[] args) {
        // 角色初始血量
        int blood = 100;
        // 本回合受到的伤害
        int hurt = 45;
        System.out.println("受到 " + hurt + " 点伤害");
        // 扣血：剩余血量 = 原血量 - 伤害
        blood = blood - hurt;
        // 判断角色是否阵亡
        if (blood <= 0) {
            System.out.println("角色阵亡");
        }
        // 没有阵亡时打印当前状态
        if (blood > 0) {
            System.out.println("角色存活，当前血量为 " + blood);
        }
    }
}

