package com.heima.ch03;

import java.util.Scanner;

// ==================== 示例代码 ====================

public class BreakKeyword {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        // 死循环 + 菜单：只有用户选择退出才结束
        while (true) {
            System.out.println("===== 黑马食堂 =====");
            System.out.println("1.宫保鸡丁 2.鱼香肉丝 3.结账退出");
            System.out.println("请输入编号：");
            int choice = sc.nextInt();
            switch (choice) {
                case 1:
                    System.out.println("宫保鸡丁已下单");
                    break;
                case 2:
                    System.out.println("鱼香肉丝已下单");
                    break;
                case 3:
                    System.out.println("欢迎下次光临");
                    break; // 这里只能跳出 switch
                default:
                    System.out.println("没有这个菜");
                    break;
            }
            // 用户选了 3 时，结束整个死循环
            if (choice == 3) {
                break;
            }
        }
    }
}

