package com.heima.ch03;

// ==================== 示例代码 ====================

public class PrintShapes {
    public static void main(String[] args) {
        // 练习1：直角三角形（第 i 行打印 i 个星号）
        for (int i = 1; i <= 5; i++) {
            for (int j = 1; j <= i; j++) {
                System.out.print("*");
            }
            System.out.println();
        }
        System.out.println("----------------");

        // 练习3：等腰三角形（第 i 行：5-i 个空格 + 2i-1 个星号）
        for (int i = 1; i <= 5; i++) {
            // 先打印空格
            for (int k = 1; k <= 5 - i; k++) {
                System.out.print(" ");
            }
            // 再打印星号
            for (int m = 1; m <= 2 * i - 1; m++) {
                System.out.print("*");
            }
            System.out.println();
        }
    }
}

