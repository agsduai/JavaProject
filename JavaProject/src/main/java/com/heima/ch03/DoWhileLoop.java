package com.heima.ch03;

// ==================== 示例代码 ====================

public class DoWhileLoop {
    public static void main(String[] args) {
        // 打印 1~5：先执行一次，再判断条件
        int i = 1;
        do {
            System.out.println(i);
            i++;
        } while (i <= 5); // 这里必须写分号

        // 条件一开始就不成立，循环体也执行了一次
        int j = 100;
        do {
            System.out.println("我至少会执行一次，j = " + j);
            j++;
        } while (j < 100);
    }
}

