package com.heima.ch03;

// ==================== 示例代码 ====================

public class NestedLoop {
    public static void main(String[] args) {
        // 打印 3 行 4 列的星号矩形
        // 外层：控制一共打印几行
        for (int i = 1; i <= 3; i++) {
            // 内层：控制每一行打印几个星号
            for (int j = 1; j <= 4; j++) {
                System.out.print("* ");
            }
            // 每行打印完换行
            System.out.println();
        }
        System.out.println("----------------");

        // 体会执行顺序：外层转 1 圈，内层完整跑一轮
        for (int i = 1; i <= 2; i++) {
            for (int j = 1; j <= 3; j++) {
                System.out.println("i = " + i + "，j = " + j);
            }
        }
    }
}

