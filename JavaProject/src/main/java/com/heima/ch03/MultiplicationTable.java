package com.heima.ch03;

// ==================== 示例代码 ====================

public class MultiplicationTable {
    public static void main(String[] args) {
        // 外层循环控制第几行（一共 9 行）
        for (int i = 1; i <= 9; i++) {
            // 内层循环控制这一行打印几列（第 i 行有 i 列）
            for (int j = 1; j <= i; j++) {
                // 打印一个式子，用制表符对齐，不换行
                System.out.print(j + "×" + i + "=" + j * i + "\t");
            }
            // 一行结束后换行
            System.out.println();
        }
    }
}

