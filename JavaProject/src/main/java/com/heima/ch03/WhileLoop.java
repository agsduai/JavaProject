package com.heima.ch03;

// ==================== 示例代码 ====================

public class WhileLoop {
    public static void main(String[] args) {
        // 打印 1~5
        int i = 1;
        while (i <= 5) {
            System.out.println(i);
            i++;
        }
        // while 的循环变量在循环外定义，结束后仍可使用
        System.out.println("循环结束后 i = " + i);

        // 用 while 求 1~100 的和
        int sum = 0;
        int j = 1;
        while (j <= 100) {
            sum += j;
            j++;
        }
        System.out.println("1~100的和：" + sum);
    }
}

