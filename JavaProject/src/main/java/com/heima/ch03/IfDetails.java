package com.heima.ch03;

// ==================== 示例代码 ====================

public class IfDetails {
    public static void main(String[] args) {
        int score = 60;
        // 细节1：不加大括号时，if 只控制紧跟的一条语句
        if (score >= 60)
            System.out.println("及格了");

        // 细节2：if 后面多写了一个分号，大括号里的内容无条件执行
        int money = 10;
        if (money > 100); {
            System.out.println("我是百万富翁");
        }

        // 细节3：大括号内定义的变量，出了大括号就失效
        if (money > 0) {
            int temp = money * 2;
            System.out.println("翻倍后：" + temp);
        }
        // System.out.println(temp); // 编译报错，temp 已超出作用域
    }
}

