package com.heima.ch03;

import java.util.Scanner;

// ==================== 示例代码 ====================

public class IfElse {
    public static void main(String[] args) {
        // 键盘录入一个整数，判断奇偶
        Scanner sc = new Scanner(System.in);
        System.out.println("请输入一个整数：");
        int num = sc.nextInt();
        // 能被 2 整除是偶数，否则是奇数
        if (num % 2 == 0) {
            System.out.println(num + " 是偶数");
        } else {
            System.out.println(num + " 是奇数");
        }
    }
}

