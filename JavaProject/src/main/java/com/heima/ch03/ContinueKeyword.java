package com.heima.ch03;

// ==================== 示例代码 ====================

public class ContinueKeyword {
    public static void main(String[] args) {
        // 练习1：打印 1~100 中的奇数，偶数直接跳过
        for (int i = 1; i <= 100; i++) {
            if (i % 2 == 0) {
                continue; // 跳过本次循环，直接进入下一圈
            }
            System.out.print(i + " ");
        }
        System.out.println();

        // 练习2：求 1~100 的和，跳过所有 7 的倍数
        int sum = 0;
        for (int i = 1; i <= 100; i++) {
            if (i % 7 == 0) {
                continue;
            }
            sum += i;
        }
        System.out.println("1~100去掉7的倍数后的和：" + sum);
    }
}

