package com.heima.ch03;

// ==================== 示例代码 ====================

public class InfiniteLoop {
    public static void main(String[] args) {
        // 死循环最常用的写法
        int count = 0;
        while (true) {
            count++;
            System.out.println("第 " + count + " 次执行");
            // 满足条件时用 break 跳出，避免真的永远循环
            if (count == 5) {
                System.out.println("执行完毕，退出循环");
                break;
            }
        }
        System.out.println("程序结束");
    }
}

