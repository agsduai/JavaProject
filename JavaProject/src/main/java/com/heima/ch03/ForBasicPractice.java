package com.heima.ch03;

// ==================== 示例代码 ====================

public class ForBasicPractice {
    public static void main(String[] args) {
        // 练习1：求 1~100 的和
        int sum = 0;
        for (int i = 1; i <= 100; i++) {
            sum += i;
        }
        System.out.println("1~100的和：" + sum);

        // 练习2：求 1~100 的偶数和
        int evenSum = 0;
        for (int i = 1; i <= 100; i++) {
            // 只累加偶数
            if (i % 2 == 0) {
                evenSum += i;
            }
        }
        System.out.println("1~100的偶数和：" + evenSum);
    }
}

