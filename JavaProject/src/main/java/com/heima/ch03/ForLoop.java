package com.heima.ch03;

// ==================== 示例代码 ====================

public class ForLoop {
    public static void main(String[] args) {
        // 打印 3 次同一句话
        for (int i = 1; i <= 3; i++) {
            System.out.println("黑马程序员 牛逼!");
        }
        System.out.println("----------------");

        // 求 1~5 的和：演示累加思想
        int sum = 0;
        for (int i = 1; i <= 5; i++) {
            sum += i;
        }
        System.out.println("1~5的和是：" + sum);
    }
}

