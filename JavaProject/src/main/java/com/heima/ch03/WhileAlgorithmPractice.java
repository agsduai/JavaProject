package com.heima.ch03;

// ==================== 示例代码 ====================

public class WhileAlgorithmPractice {
    public static void main(String[] args) {
        // 练习1：纸张折叠超过珠峰高度
        double paper = 0.0001; // 纸张厚度 0.1 毫米，换算成米
        int peak = 8844430;    // 珠穆朗玛峰高度（米）
        int count = 0;         // 对折次数
        while (paper <= peak) {
            paper = paper * 2; // 每对折一次厚度翻倍
            count++;
        }
        System.out.println("对折 " + count + " 次后超过珠峰高度");
        System.out.println("----------------");

        // 练习3：数位求和
        int num = 123;
        int sum = 0;
        while (num > 0) {
            sum += num % 10; // 取出个位累加
            num = num / 10;  // 去掉个位
        }
        System.out.println("123 各位数字之和：" + sum);
    }
}

