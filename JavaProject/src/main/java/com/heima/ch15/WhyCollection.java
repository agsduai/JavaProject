package com.heima.ch15;

import java.util.ArrayList;

// ==================== 示例代码 ====================

public class WhyCollection {
    public static void main(String[] args) {
        // 数组：长度固定，第 4 个元素放不进去
        int[] arr = new int[3];
        arr[0] = 10;
        arr[1] = 20;
        arr[2] = 30;
        System.out.println("数组长度：" + arr.length); // 3，永远是 3

        // 集合：长度可变，想加多少加多少
        ArrayList<String> list = new ArrayList<>();
        list.add("张三");
        list.add("李四");
        list.add("王五");
        list.add("赵六");
        System.out.println("集合元素：" + list);
        System.out.println("集合大小：" + list.size()); // 4，可以继续增长

        // 集合只能存引用类型，基本类型会自动装箱
        ArrayList<Integer> scores = new ArrayList<>();
        scores.add(90);      // 自动装箱为 Integer.valueOf(90)
        scores.add(85);
        int first = scores.get(0); // 自动拆箱为 int
        System.out.println("第一门成绩：" + first);
    }
}

