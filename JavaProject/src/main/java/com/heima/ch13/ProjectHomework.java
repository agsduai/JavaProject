// ==================== 示例代码 ====================

public class ProjectHomework {
    public static void main(String[] args) {
        // 游戏界面常用的小工具：重复字符生成分隔线
        System.out.println(getLine('=', 30));
        System.out.println("       黑马格斗小游戏       ");
        System.out.println(getLine('=', 30));

        // 生成一段用 ★ 填充的星级评价
        System.out.println("本次战斗评价：" + getStars(3));
    }

    // 生成重复 count 个字符的字符串
    public static String getLine(char c, int count) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < count; i++) {
            sb.append(c);
        }
        return sb.toString();
    }

    // 生成 count 颗星的字符串
    public static String getStars(int count) {
        return getLine('★', count);
    }
}

